import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const html = await readFile(new URL("../index.html", import.meta.url), "utf8");
const ui = await readFile(new URL("../js/ui.js", import.meta.url), "utf8");
const robots = await readFile(new URL("../robots.txt", import.meta.url), "utf8");
const sitemap = await readFile(new URL("../sitemap.xml", import.meta.url), "utf8");

assert.match(html, /<title>GISMap Online: Free Geospatial Application<\/title>/);
assert.match(html, /property="og:title" content="GISMap Online: Free Geospatial Application"/);
assert.match(html, /name="twitter:title" content="GISMap Online: Free Geospatial Application"/);
assert.doesNotMatch(html, /Free 3D ArcGIS REST &amp; GeoJSON Viewer/);
assert.match(html, /<link rel="canonical" href="https:\/\/gismap\.online\/" \/>/);
assert.match(html, /property="og:image"/);
assert.match(html, /name="twitter:card" content="summary_large_image"/);
assert.match(html, /<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
const structuredData = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
assert.deepEqual(structuredData["@type"], ["SoftwareApplication", "WebApplication"]);
assert.equal(structuredData.name, "GISMap Online");
assert.equal(structuredData.isAccessibleForFree, true);
assert.equal(structuredData.author.name, "Silas Toms");
assert.match(html, /id="welcome-title" data-brand-name>GISMap Online/);
assert.match(html, /id="welcome-close"[^>]*aria-label="Dismiss introduction"/);
assert.doesNotMatch(ui, /welcomePanel\.hidden\s*=\s*Boolean\(layers\.length\)/);
assert.match(ui, /button\.closest\("#welcome-panel"\)/);
assert.match(ui, /if \(open\) this\.#dismissWelcome\(\)/);
assert.match(ui, /keepWelcomeForSharedExample/);
assert.match(ui, /if \(layers\.length && \(!this\.keepWelcomeForSharedExample \|\| this\.mobileMedia\.matches\)\) this\.#dismissWelcome\(\)/);
// The welcome panel is never remembered as dismissed (other session state, such as reopening the basemap gallery, may use sessionStorage).
assert.doesNotMatch(ui, /WELCOME_DISMISSED_KEY|sessionStorage[^\n]*welcome/i);
assert.match(ui, /data-ai-selection/);
assert.match(ui, /selectedResults/);
assert.match(html, /id="insights-ai"[^>]*title="AI Insights"/);
assert.match(html, /id="utility-tabs"/);
assert.match(html, /<header class="mobile-map-brand"[^>]*aria-label="GISMap Online"/);
assert.match(html, /id="map-navigation-toggle"/);
assert.match(html, /data-empty-action="data-popular">Try an example/);
assert.match(html, /data-mobile-workflow="briefing"[^>]*aria-label="Briefing"/);
assert.match(html, /aria-label="Mobile workflows"/);
assert.match(ui, /mobileDrawerContent\.inert/);
assert.match(html, /data-widget="legend">Legend/);
assert.match(ui, /const DOCKABLE_PANELS = \{ places: "Places", bookmarks: "Bookmarks", draw: "Draw", intelligence: "Intelligence", layers: "Layers", observations: "Notes & Tasks" \}/);
assert.match(ui, /button\.innerHTML = dockIcon\("dock"\)/);
assert.match(html, /data-utility-pane="style"/);
assert.match(ui, /#openDrawUtility/);
assert.match(ui, /#openSymbologyUtility/);
assert.match(ui, /lastAIResponseText/);
assert.match(ui, /Open in right panel/);
assert.match(ui, /navigationLayout === "top"\) this\.#openIntelligenceUtility/);
assert.match(ui, /panelManager\?\.move\("content:intelligence"/);
assert.match(ui, /panelManager\?\.restore\("content:intelligence"/);
assert.doesNotMatch(ui, /const targets = \[document\.querySelector\("#intelligence-content"\), document\.querySelector\("#utility-intelligence-content"\)\]/, "Intelligence must have one live render target.");
assert.match(ui, /lastAIQueryText/);
assert.match(ui, /goToFeature\(result\)/);
assert.match(ui, /Selected data query/);
assert.match(ui, /data-close-utility-tab/);
assert.match(ui, /gesturestart/, "map canvas blocks browser gesture zooming");
assert.match(robots, /Sitemap: https:\/\/gismap\.online\/sitemap\.xml/);
assert.match(sitemap, /<loc>https:\/\/gismap\.online\/<\/loc>/);
